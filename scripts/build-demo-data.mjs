// Builds public/demo-data.js for the no-key demo (public/tour.html and go.html?demo=…).
// Everything comes from the real rules and templates, so the demo can never drift from the product:
//   first alert  = stage1Text()        (the fixed text real users get)
//   action       = decideAction()      (the real safety rules)
//   next steps   = fallbackGuidance()  (the prepared text; on the live service Gemini 4 Argon writes it)
//   shelters     = shelterLayerFor()   (the GSI layer the real page searches)
// Run: npm run demo-data   (test/demo-data.test.js fails if the file is stale)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { decideAction, shelterLayerFor, scaleLabel } from '../api/_lib/hazards.js';
import { fallbackGuidance, stage1Text, LANGUAGES, ui } from '../api/_lib/templates.js';
import { prefByCode } from '../api/_lib/areas.js';

const SCENARIOS = {
  quake: {
    label: 'Earthquake in Tokyo',
    hazard: 'earthquake',
    pref: '13',
    area: { scale: 55 },
    facts: { epicenter: '東京湾', magnitude: 6.8, source: 'Japan Meteorological Agency' },
    feed: 'Earthquake Early Warning + seismic intensity report',
  },
  tsunami: {
    label: 'Tsunami warning in Chiba',
    hazard: 'tsunami',
    pref: '12',
    area: { grade: 'Warning', region: '千葉県九十九里・外房', height: '3m' },
    facts: { epicenter: '千葉県東方沖', magnitude: 7.4, source: 'Japan Meteorological Agency' },
    feed: 'Tsunami warning',
  },
  typhoon: {
    label: 'Typhoon in Okinawa',
    hazard: 'typhoon',
    pref: '47',
    area: { level: 4 },
    facts: { name: 'Typhoon No. 22', source: 'Japan Meteorological Agency' },
    feed: 'Storm and heavy-rain warnings, alert level 4',
  },
};

export function buildDemoData() {
  const langs = Object.keys(LANGUAGES);
  const scenarios = {};
  for (const [key, sc] of Object.entries(SCENARIOS)) {
    const pref = prefByCode(sc.pref);
    const action = decideAction(sc.hazard, sc.area);
    scenarios[key] = {
      ...sc,
      pref: { code: pref.code, en: pref.en, ja: pref.ja },
      area: { prefCode: pref.code, ...sc.area, ...(sc.area.scale && { intensity: scaleLabel(sc.area.scale) }) },
      action,
      shelterLayer: shelterLayerFor(sc.hazard, action),
      stage1: Object.fromEntries(langs.map((l) => [l, stage1Text(sc.hazard, l)])),
      guidance: Object.fromEntries(langs.map((l) => [l, fallbackGuidance(action, l)])),
    };
  }
  return { languages: LANGUAGES, drillLabel: Object.fromEntries(langs.map((l) => [l, ui('drill', l)])), scenarios };
}

export function renderDemoData() {
  return `// Generated by scripts/build-demo-data.mjs from the real rules and templates. Do not edit.\nwindow.DAIBOJU_DEMO = ${JSON.stringify(buildDemoData(), null, 1)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('../public/demo-data.js', import.meta.url), renderDemoData());
  console.log('wrote public/demo-data.js');
}
